from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class AnalysisResult:
    """
    Holds the complete result of one structured-data analysis.
    This structure is designed so a future React frontend can
    read it directly and render charts without extra processing.
    """
    # The original question the user asked
    question: str

    # Which dataset and sheet this result came from
    dataset_name: str
    sheet_name: str

    # Type of analysis performed (e.g. "ranking", "time_series", "correlation")
    analysis_type: str

    # The actual computed data as a list of dicts (table-friendly, JSON-friendly)
    result_data: List[Dict[str, Any]] = field(default_factory=list)

    # A single scalar result when appropriate (e.g. total sales = 1_800_000)
    scalar_result: Optional[Any] = None

    # Human-friendly explanation generated by the LLM
    explanation: str = ""

    # Structured visualization specification for future React charts
    visualization: Dict[str, Any] = field(default_factory=dict)

    # Non-fatal warnings (e.g. "3 rows had missing values and were excluded")
    warnings: List[str] = field(default_factory=list)

    # Metadata about the analysis execution
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Return a plain dict for JSON serialization or display."""
        return {
            "question": self.question,
            "dataset_name": self.dataset_name,
            "sheet_name": self.sheet_name,
            "analysis_type": self.analysis_type,
            "result_data": self.result_data,
            "scalar_result": self.scalar_result,
            "explanation": self.explanation,
            "visualization": self.visualization,
            "warnings": self.warnings,
            "metadata": self.metadata,
        }
